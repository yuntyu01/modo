/** 지원 언어. 새 언어는 src/locales/<code>.ts(모든 키) + 아래 세 곳 + Android res/values-<code> + iOS 위젯(NotesStore.L)에 더한다. */
export const LANGS = ['ko', 'en', 'ja', 'zh'] as const;
export type Lang = (typeof LANGS)[number];
/** 언어 고르기 화면에 그 언어 자신의 이름으로 보인다 */
export const LANG_NAMES: Record<Lang, string> = { ko: '한국어', en: 'English', ja: '日本語', zh: '简体中文' };
const DICTS: Record<Lang, Record<StringKey, string>> = { ko, en, ja, zh };

/**
 * 'system'이면 기기 언어 중 지원하는 첫 언어(없으면 영어).
 * getLocales()는 네이티브를 부르는 꽤 비싼 호출이라(Android는 부를 때마다 숫자·통화 형식까지 만든다) 화면에서는 부르지 말고
 * AppContext의 lang(기기 언어가 바뀔 때만 다시 고른다)을 쓴다.
 */
export function resolveLang(pref: 'system' | Lang, locales: readonly Locale[] = getLocales()): Lang {
  if (pref !== 'system' && (LANGS as readonly string[]).includes(pref)) return pref;
  for (const l of locales) {
    const code = l.languageCode?.toLowerCase();
    if (code && (LANGS as readonly string[]).includes(code)) return code as Lang;
  }
  return 'en';
}

export function translator(lang: Lang) {
  const dict = DICTS[lang] ?? en;
  return (key: StringKey, vars?: Record<string, string | number>) => {
    let s = dict[key] ?? en[key] ?? ko[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** 오류를 사용자 언어로: 아는 code(err_<code>)면 번역, 아니면 받은 문구 그대로 */
export function errorText(e: unknown, t: (key: StringKey, vars?: Record<string, string | number>) => string): string {
  if (e instanceof CodedError) return codeText(e.code, e.message, t, (e as { status?: number }).status);
  return e instanceof Error ? e.message : String(e);
}

export function codeText(
  code: string | undefined,
  fallback: string,
  t: (key: StringKey, vars?: Record<string, string | number>) => string,
  status?: number,
) {
  const key = `err_${code}` as StringKey;
  return code && key in ko ? t(key, { status: status ?? '' }) : fallback;
}

