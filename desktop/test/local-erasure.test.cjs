const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createLocalErasure } = require('../local-erasure.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'modo-erasure-'));
const backups = path.join(root, 'backups');
fs.mkdirSync(backups);
fs.writeFileSync(path.join(backups, 'naegirok-v4-isolated.db'), 'disposable fixture');
fs.writeFileSync(path.join(backups, 'user-export.json'), 'keep');
let busy = 1;
const erasure = createLocalErasure(root, { all: () => [{ busy }] });
assert.throws(() => erasure.accepted(), /busy/);
assert.ok(fs.existsSync(path.join(root, 'account-erasure.pending')));
assert.equal(fs.existsSync(path.join(backups, 'naegirok-v4-isolated.db')), false);
assert.ok(fs.existsSync(path.join(backups, 'user-export.json')));
busy = 0;
erasure.retry();
assert.equal(fs.existsSync(path.join(root, 'account-erasure.pending')), false);
erasure.retry();
fs.rmSync(root, { recursive: true });
console.log('local-erasure: managed backups removed; unrelated exports preserved; interrupted cleanup retried');
